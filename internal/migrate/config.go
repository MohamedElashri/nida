package migrate

import (
	"fmt"
	"slices"
	"strings"

	toml "github.com/pelletier/go-toml/v2"
)

// Config builds the migrated site's config.toml. Keys keep the order they
// were set in, so the file reads top to bottom like a hand-written one,
// and only settings that differ from Nida's defaults need to be set.
type Config struct {
	root       Table
	tables     []*Table
	taxonomies []*Table
}

// Table is one TOML table of the config.
type Table struct {
	name    string
	keys    []string
	values  map[string]any
	comment string
}

// Set sets a key in the table, keeping its original position if it was
// already set.
func (t *Table) Set(key string, value any) {
	if t.values == nil {
		t.values = map[string]any{}
	}
	if _, ok := t.values[key]; !ok {
		t.keys = append(t.keys, key)
	}
	t.values[key] = value
}

// Get returns a key's value.
func (t *Table) Get(key string) (any, bool) {
	v, ok := t.values[key]
	return v, ok
}

// Comment sets a comment written above the table header.
func (t *Table) Comment(text string) { t.comment = text }

// Set sets a top-level key.
func (c *Config) Set(key string, value any) { c.root.Set(key, value) }

// Get returns a top-level key's value.
func (c *Config) Get(key string) (any, bool) { return c.root.Get(key) }

// Table returns the named table, creating it. Nested tables use dotted
// names, such as "pipeline.scss".
func (c *Config) Table(name string) *Table {
	for _, t := range c.tables {
		if t.name == name {
			return t
		}
	}
	t := &Table{name: name}
	c.tables = append(c.tables, t)
	return t
}

// HasTable reports whether a table has been created.
func (c *Config) HasTable(name string) bool {
	return slices.ContainsFunc(c.tables, func(t *Table) bool { return t.name == name })
}

// Taxonomy returns the [[taxonomies]] entry for name, creating it.
func (c *Config) Taxonomy(name string) *Table {
	for _, t := range c.taxonomies {
		if t.values["name"] == name {
			return t
		}
	}
	t := &Table{name: "taxonomies"}
	t.Set("name", name)
	c.taxonomies = append(c.taxonomies, t)
	return t
}

// TaxonomyNames returns the configured taxonomy names in order.
func (c *Config) TaxonomyNames() []string {
	var names []string
	for _, t := range c.taxonomies {
		names = append(names, t.values["name"].(string))
	}
	return names
}

// Bytes renders config.toml.
func (c *Config) Bytes() ([]byte, error) {
	var b strings.Builder
	b.WriteString("# Generated by nida migrate. See MIGRATION.md for what changed.\n\n")
	if err := writeKeys(&b, &c.root); err != nil {
		return nil, err
	}
	for _, t := range c.taxonomies {
		b.WriteString("\n[[taxonomies]]\n")
		if err := writeKeys(&b, t); err != nil {
			return nil, err
		}
	}
	for _, t := range c.tables {
		if len(t.keys) == 0 {
			continue
		}
		b.WriteString("\n")
		if t.comment != "" {
			for _, line := range strings.Split(t.comment, "\n") {
				fmt.Fprintf(&b, "# %s\n", line)
			}
		}
		fmt.Fprintf(&b, "[%s]\n", t.name)
		if err := writeKeys(&b, t); err != nil {
			return nil, err
		}
	}
	return []byte(b.String()), nil
}

func writeKeys(b *strings.Builder, t *Table) error {
	for _, key := range t.keys {
		value, err := inlineValue(t.values[key])
		if err != nil {
			return fmt.Errorf("encode config key %q: %w", key, err)
		}
		fmt.Fprintf(b, "%s = %s\n", tomlKey(key), value)
	}
	return nil
}

// inlineValue encodes a value on one line, with maps as inline tables, so
// nested values stay inside the table they belong to.
func inlineValue(value any) (string, error) {
	switch v := value.(type) {
	case map[string]any:
		parts := make([]string, 0, len(v))
		for _, k := range sortedKeys(v) {
			item, err := inlineValue(v[k])
			if err != nil {
				return "", err
			}
			parts = append(parts, fmt.Sprintf("%s = %s", tomlKey(k), item))
		}
		if len(parts) == 0 {
			return "{}", nil
		}
		return "{ " + strings.Join(parts, ", ") + " }", nil
	case []any:
		parts := make([]string, 0, len(v))
		for _, item := range v {
			encoded, err := inlineValue(item)
			if err != nil {
				return "", err
			}
			parts = append(parts, encoded)
		}
		return "[" + strings.Join(parts, ", ") + "]", nil
	case []string:
		items := make([]any, len(v))
		for i, item := range v {
			items[i] = item
		}
		return inlineValue(items)
	case []map[string]any:
		items := make([]any, len(v))
		for i, m := range v {
			items[i] = m
		}
		return inlineValue(items)
	}
	if str, ok := value.(string); ok {
		return tomlString(str), nil
	}
	encoded, err := toml.Marshal(map[string]any{"v": value})
	if err != nil {
		return "", err
	}
	text := strings.TrimSpace(string(encoded))
	if !strings.HasPrefix(text, "v = ") {
		return "", fmt.Errorf("cannot encode %T inline", value)
	}
	return strings.TrimPrefix(text, "v = "), nil
}

// tomlString encodes a TOML basic string. go-toml prefers literal
// 'strings', which look out of place in hand-written files.
func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r == '\r':
			b.WriteString(`\r`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
