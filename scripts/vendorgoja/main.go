// Command vendorgoja keeps third_party/goja, Nida's patched copy of the goja
// JavaScript engine, in sync with upstream.
//
// The copy is upstream goja at the version third_party/goja.version pins,
// without tests or go.mod, with third_party/goja.patch applied, every file
// limited to 64-bit platforms, and goja's imports of its own packages moved
// under Nida's module path. The copy is part of the nida module, so go.mod
// needs no replace directive, which go install ...@latest refuses.
//
//	go run ./scripts/vendorgoja                  rebuild the copy from the pinned version
//	go run ./scripts/vendorgoja -update master   move to a newer upstream commit
//	go run ./scripts/vendorgoja -check           fail if the copy differs from upstream + patch
//	go run ./scripts/vendorgoja -outdated        print the newest upstream version, if newer
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const (
	module      = "github.com/dop251/goja"
	destDir     = "third_party/goja"
	patchFile   = "third_party/goja.patch"
	versionFile = "third_party/goja.version"
	// vendored is the copy's import path inside the nida module.
	vendored = "github.com/MohamedElashri/nida/" + destDir
)

// skipDirs and skipFile drop what Nida does not build: tests, test data,
// upstream CI, the goja command-line tool, and goja's go.mod and go.sum,
// which would make the copy a module of its own. skipDirs holds paths
// relative to the module root.
var skipDirs = map[string]bool{".github": true, "testdata": true, "goja": true}

// arch64 lists the 64-bit architectures goja is built for. goja converts
// int64 to int throughout, which only loses data where int is 32 bits, so
// the copy builds only where int is 64 bits. The list leaves out loong64,
// which CodeQL does not know, so CodeQL can see that every file is 64-bit
// and does not flag those conversions.
const arch64 = "amd64 || arm64 || mips64 || mips64le || ppc64 || ppc64le || riscv64 || s390x || wasm"

// constraint64 is the build constraint for every file. CodeQL reads only
// the old "// +build" syntax, so the files carry both lines.
var constraint64 = "//go:build " + arch64 + "\n// +build " + strings.ReplaceAll(arch64, " || ", " ") + "\n\n"

// guardFile makes a build on any other platform fail with a clear message
// instead of "build constraints exclude all Go files".
const guardFile = "nida_requires_64bit.go"

const guardSource = "// Code generated by scripts/vendorgoja. DO NOT EDIT.\n\n" +
	"//go:build !(" + arch64 + ")\n\n" +
	"package goja\n\n" +
	"// Nida's copy of goja builds only on 64-bit platforms; see\n" +
	"// scripts/vendorgoja.\n" +
	"var _ = nida_requires_a_64_bit_platform\n"

func skipFile(name string) bool {
	return strings.HasSuffix(name, "_test.go") || strings.HasSuffix(name, ".sh") || strings.HasPrefix(name, ".") ||
		name == "go.mod" || name == "go.sum"
}

func main() {
	update := flag.String("update", "", "upstream version or branch to move to, such as master")
	check := flag.Bool("check", false, "verify the copy instead of writing it")
	outdated := flag.Bool("outdated", false, "print the newest upstream version if it is newer than the pinned one")
	flag.Parse()
	if *check && *update != "" {
		fmt.Fprintln(os.Stderr, "vendorgoja: -check and -update cannot be combined")
		os.Exit(2)
	}
	if err := run(*update, *check, *outdated); err != nil {
		fmt.Fprintln(os.Stderr, "vendorgoja:", err)
		os.Exit(1)
	}
}

func run(update string, check, outdated bool) error {
	pinned, err := requiredVersion()
	if err != nil {
		return err
	}
	if outdated {
		latest, err := download("master")
		if err != nil {
			return err
		}
		if latest.Version != pinned {
			fmt.Println(latest.Version)
		}
		return nil
	}

	version := pinned
	if update != "" {
		version = update
	}
	mod, err := download(version)
	if err != nil {
		return err
	}
	tmp, err := os.MkdirTemp("", "vendorgoja-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	if err := copyTree(mod.Dir, tmp); err != nil {
		return err
	}
	if err := applyPatch(tmp); err != nil {
		return fmt.Errorf("%s no longer applies to goja %s: %w\nupdate the patch against the new version, then run again", patchFile, mod.Version, err)
	}
	if err := limitTo64Bit(tmp); err != nil {
		return err
	}
	if err := rewriteImports(tmp); err != nil {
		return err
	}

	if check {
		diffs, err := compareTrees(tmp, destDir)
		if err != nil {
			return err
		}
		if len(diffs) > 0 {
			return fmt.Errorf("%s differs from goja %s with %s applied:\n  %s\nrun: go run ./scripts/vendorgoja",
				destDir, pinned, patchFile, strings.Join(diffs, "\n  "))
		}
		fmt.Printf("%s matches goja %s with %s applied\n", destDir, pinned, patchFile)
		return nil
	}

	if err := os.RemoveAll(destDir); err != nil {
		return err
	}
	if err := copyTree(tmp, destDir); err != nil {
		return err
	}
	if mod.Version != pinned {
		if err := os.WriteFile(versionFile, []byte(mod.Version+"\n"), 0o644); err != nil {
			return err
		}
		// goja's dependencies are nida's, and may have changed.
		if err := goCmd(nil, "mod", "tidy"); err != nil {
			return err
		}
	}
	fmt.Printf("wrote %s from goja %s with %s applied\n", destDir, mod.Version, patchFile)
	return nil
}

type moduleInfo struct {
	Version string
	Dir     string
	Error   string
}

func download(version string) (moduleInfo, error) {
	var out bytes.Buffer
	cmd := exec.Command("go", "mod", "download", "-json", module+"@"+version)
	cmd.Stdout = &out
	cmd.Stderr = os.Stderr
	runErr := cmd.Run()
	var info moduleInfo
	if err := json.Unmarshal(out.Bytes(), &info); err != nil {
		if runErr != nil {
			return info, runErr
		}
		return info, err
	}
	if info.Error != "" {
		return info, errors.New(info.Error)
	}
	return info, runErr
}

func requiredVersion() (string, error) {
	data, err := os.ReadFile(versionFile)
	if err != nil {
		return "", err
	}
	version := strings.TrimSpace(string(data))
	if version == "" {
		return "", fmt.Errorf("%s is empty", versionFile)
	}
	return version, nil
}

func goCmd(stdout *bytes.Buffer, args ...string) error {
	cmd := exec.Command("go", args...)
	cmd.Stderr = os.Stderr
	if stdout != nil {
		cmd.Stdout = stdout
	} else {
		cmd.Stdout = os.Stdout
	}
	return cmd.Run()
}

func copyTree(src, dst string) error {
	return filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		if d.IsDir() {
			if skipDirs[filepath.ToSlash(rel)] || d.Name() == "testdata" {
				return filepath.SkipDir
			}
			return os.MkdirAll(filepath.Join(dst, rel), 0o755)
		}
		if skipFile(d.Name()) {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(dst, rel), data, 0o644)
	})
}

func applyPatch(dir string) error {
	patch, err := filepath.Abs(patchFile)
	if err != nil {
		return err
	}
	// Outside a git repository, git apply works like patch(1).
	cmd := exec.Command("git", "apply", "--verbose", patch)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GIT_CEILING_DIRECTORIES="+filepath.Dir(dir))
	cmd.Stdout = os.Stderr
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

// limitTo64Bit adds the arch64 build constraint to every Go file and writes
// the guard file for other platforms.
func limitTo64Bit(dir string) error {
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.Contains(data, []byte("//go:build")) {
			return fmt.Errorf("%s already has a build constraint; combine it with arch64 in scripts/vendorgoja", path)
		}
		return os.WriteFile(path, append([]byte(constraint64), data...), 0o644)
	})
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, guardFile), []byte(guardSource), 0o644)
}

// rewriteImports moves goja's imports of its own packages, such as
// github.com/dop251/goja/parser, under the copy's path in the nida module.
func rewriteImports(dir string) error {
	return filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		moved := bytes.ReplaceAll(data, []byte(`"`+module+`"`), []byte(`"`+vendored+`"`))
		moved = bytes.ReplaceAll(moved, []byte(`"`+module+`/`), []byte(`"`+vendored+`/`))
		if bytes.Equal(moved, data) {
			return nil
		}
		// The new path sorts differently, so the imports are sorted again
		// to keep the copy gofmt-clean.
		formatted, err := format.Source(moved)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		return os.WriteFile(path, formatted, 0o644)
	})
}

func compareTrees(want, got string) ([]string, error) {
	wantFiles, err := listFiles(want)
	if err != nil {
		return nil, err
	}
	gotFiles, err := listFiles(got)
	if err != nil {
		return nil, err
	}
	var diffs []string
	for name, data := range wantFiles {
		have, ok := gotFiles[name]
		switch {
		case !ok:
			diffs = append(diffs, "missing "+name)
		case !bytes.Equal(data, have):
			diffs = append(diffs, "changed "+name)
		}
	}
	for name := range gotFiles {
		if _, ok := wantFiles[name]; !ok {
			diffs = append(diffs, "extra "+name)
		}
	}
	sort.Strings(diffs)
	return diffs, nil
}

func listFiles(root string) (map[string][]byte, error) {
	files := map[string][]byte{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		data, err := os.ReadFile(path)
		files[filepath.ToSlash(rel)] = data
		return err
	})
	return files, err
}
