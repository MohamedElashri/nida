// Command vendorjs writes the JavaScript libraries, stylesheets, and fonts
// embedded in nida from the npm packages pinned in third_party/js.
//
// third_party/js/package-lock.json is the source of truth: Dependabot opens
// pull requests that bump it, and this command downloads each package
// tarball, checks it against the lockfile's integrity hash, and writes the
// files below together with the Go version constants.
//
//	go run ./scripts/vendorjs          write the files
//	go run ./scripts/vendorjs -check   fail if the files differ from the lockfile
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"crypto/sha512"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"strings"
	"time"
)

const lockfile = "third_party/js/package-lock.json"

// file is one file taken from an npm package. A .gz destination is written
// gzipped and compared by content, so recompressing with another Go version
// is not a change.
type file struct{ pkg, from, to string }

var files = []file{
	{pkg: "pele", from: "dist/pele.global.js", to: "internal/diagram/files/pele.global.js.gz"},
	{pkg: "pele", from: "LICENSE", to: "internal/diagram/files/LICENSE"},
	{pkg: "temml", from: "dist/temml.min.js", to: "internal/mathml/files/temml.min.js.gz"},
	{pkg: "temml", from: "LICENSE", to: "internal/mathml/files/LICENSE"},
	{pkg: "temml", from: "dist/Temml-Latin-Modern.css", to: "internal/bundled/files/temml/Temml-Latin-Modern.css"},
	{pkg: "temml", from: "dist/Temml-Local.css", to: "internal/bundled/files/temml/Temml-Local.css"},
	{pkg: "temml", from: "dist/Temml.woff2", to: "internal/bundled/files/temml/Temml.woff2"},
	{pkg: "temml", from: "LICENSE", to: "internal/bundled/files/temml/LICENSE"},
}

// pinned are files that no npm package ships. They are checked by hash and
// downloaded only when missing or changed.
var pinned = []struct{ url, to, sha256 string }{
	{
		// Latin Modern Math 1.959 from the Temml repository's site assets.
		url:    "https://raw.githubusercontent.com/ronkok/Temml/3c2d0789d02bd5c92572aa222fc54761ebbedb2d/site/assets/latinmodernmath.woff2",
		to:     "internal/bundled/files/temml/latinmodernmath.woff2",
		sha256: "0c1e844b33b8811709b462102e6ce3b1af800a82028bc1a7514878c362d556d5",
	},
	{
		url:    "https://www.gust.org.pl/projects/e-foundry/licenses/GUST-FONT-LICENSE.txt",
		to:     "internal/bundled/files/temml/GUST-FONT-LICENSE.txt",
		sha256: "5eb61bb836bb1845ef668717cb15b382e997748ce2629e4388cc5e4c3fa4e433",
	},
}

// versions are the Go constants that carry each package's version.
var versions = []struct{ pkg, to, goPkg, name, doc string }{
	{pkg: "pele", to: "internal/diagram/version.go", goPkg: "diagram", name: "PeleVersion",
		doc: "PeleVersion is the bundled Pele release."},
	{pkg: "temml", to: "internal/bundled/version.go", goPkg: "bundled", name: "TemmlVersion",
		doc: "TemmlVersion is the bundled Temml release, whose script is in package\n// mathml and whose stylesheets and fonts are here."},
}

var client = &http.Client{Timeout: 2 * time.Minute}

func main() {
	check := flag.Bool("check", false, "verify the files instead of writing them")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "vendorjs:", err)
		os.Exit(1)
	}
}

type lockEntry struct {
	Version, Resolved, Integrity string
}

func run(check bool) error {
	data, err := os.ReadFile(lockfile)
	if err != nil {
		return err
	}
	var lock struct {
		Packages map[string]lockEntry
	}
	if err := json.Unmarshal(data, &lock); err != nil {
		return fmt.Errorf("%s: %w", lockfile, err)
	}

	packages := map[string]map[string][]byte{}
	want := map[string][]byte{}
	var order []string
	for _, f := range files {
		if packages[f.pkg] == nil {
			entry, ok := lock.Packages["node_modules/"+f.pkg]
			if !ok {
				return fmt.Errorf("%s does not list %s", lockfile, f.pkg)
			}
			contents, err := fetchPackage(f.pkg, entry)
			if err != nil {
				return err
			}
			packages[f.pkg] = contents
		}
		content, ok := packages[f.pkg][f.from]
		if !ok {
			return fmt.Errorf("%s %s has no %s; update the file list in scripts/vendorjs", f.pkg, lock.Packages["node_modules/"+f.pkg].Version, f.from)
		}
		want[f.to] = content
		order = append(order, f.to)
	}
	for _, v := range versions {
		src := fmt.Sprintf("// Code generated by scripts/vendorjs from %s. DO NOT EDIT.\n\npackage %s\n\n// %s\nconst %s = %q\n",
			lockfile, v.goPkg, v.doc, v.name, lock.Packages["node_modules/"+v.pkg].Version)
		formatted, err := format.Source([]byte(src))
		if err != nil {
			return err
		}
		want[v.to] = formatted
		order = append(order, v.to)
	}

	var stale []string
	for _, to := range order {
		same, err := matches(to, want[to])
		if err != nil {
			return err
		}
		if same {
			continue
		}
		stale = append(stale, to)
		if !check {
			if err := write(to, want[to]); err != nil {
				return err
			}
		}
	}
	for _, p := range pinned {
		ok, err := hashMatches(p.to, p.sha256)
		if err != nil {
			return err
		}
		if ok {
			continue
		}
		stale = append(stale, p.to)
		if !check {
			if err := fetchPinned(p.url, p.to, p.sha256); err != nil {
				return err
			}
		}
	}

	switch {
	case check && len(stale) > 0:
		return fmt.Errorf("embedded files do not match %s:\n  %s\nrun: make vendor-js", lockfile, strings.Join(stale, "\n  "))
	case check:
		fmt.Printf("embedded files match %s\n", lockfile)
	case len(stale) == 0:
		fmt.Println("embedded files are up to date")
	default:
		fmt.Printf("wrote:\n  %s\n", strings.Join(stale, "\n  "))
	}
	return nil
}

// fetchPackage downloads an npm tarball, checks its integrity, and returns
// its files by path within the package.
func fetchPackage(name string, entry lockEntry) (map[string][]byte, error) {
	algo, sum, ok := strings.Cut(entry.Integrity, "-")
	if !ok || algo != "sha512" {
		return nil, fmt.Errorf("%s: unsupported integrity %q", name, entry.Integrity)
	}
	tarball, err := get(entry.Resolved)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	digest := sha512.Sum512(tarball)
	if base64.StdEncoding.EncodeToString(digest[:]) != sum {
		return nil, fmt.Errorf("%s: %s does not match the lockfile's integrity hash", name, entry.Resolved)
	}

	gz, err := gzip.NewReader(bytes.NewReader(tarball))
	if err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	contents := map[string][]byte{}
	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		if hdr.Typeflag != tar.TypeReg {
			continue
		}
		// npm tarballs put everything under one top directory, usually package/.
		_, rel, ok := strings.Cut(path.Clean(hdr.Name), "/")
		if !ok {
			continue
		}
		data, err := io.ReadAll(tr)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		contents[rel] = data
	}
	return contents, nil
}

func fetchPinned(url, to, want string) error {
	data, err := get(url)
	if err != nil {
		return err
	}
	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != want {
		return fmt.Errorf("%s has sha256 %s, want %s; if the change is expected, update the hash in scripts/vendorjs", url, got, want)
	}
	return write(to, data)
}

func get(url string) ([]byte, error) {
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

func matches(to string, want []byte) (bool, error) {
	have, err := os.ReadFile(to)
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if strings.HasSuffix(to, ".gz") {
		r, err := gzip.NewReader(bytes.NewReader(have))
		if err != nil {
			return false, nil
		}
		if have, err = io.ReadAll(r); err != nil {
			return false, nil
		}
	}
	return bytes.Equal(have, want), nil
}

func hashMatches(to, want string) (bool, error) {
	have, err := os.ReadFile(to)
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	sum := sha256.Sum256(have)
	return hex.EncodeToString(sum[:]) == want, nil
}

func write(to string, data []byte) error {
	if strings.HasSuffix(to, ".gz") {
		var buf bytes.Buffer
		zw, err := gzip.NewWriterLevel(&buf, gzip.BestCompression)
		if err != nil {
			return err
		}
		if _, err := zw.Write(data); err != nil {
			return err
		}
		if err := zw.Close(); err != nil {
			return err
		}
		data = buf.Bytes()
	}
	if err := os.MkdirAll(filepath.Dir(to), 0o755); err != nil {
		return err
	}
	return os.WriteFile(to, data, 0o644)
}
